#!/usr/bin/env bash
# Regenerate BENCHMARK.md from a full run over the committed corpora.
#
# Reproducibility: the detector runs --offline against corpus/registry-snapshot,
# a COMMITTED pin of PyPI verdicts. A fresh clone reproduces the numbers exactly,
# with no network and no credentials. Corpus freshness is a separate question,
# answered independently by `python3 -m bench verify-seeded` (live, cache-bypassing).
#
# Usage: scripts/benchmark.sh [--live]   (--live allows registry lookups)
set -euo pipefail
cd "$(dirname "$0")/.."

OFFLINE="--offline"
MODE="offline (warm cache)"
if [[ "${1:-}" == "--live" ]]; then
  OFFLINE=""
  MODE="live (registry lookups permitted)"
fi

command -v go >/dev/null || { echo "go not found on PATH" >&2; exit 1; }
go build -o bin/safecommit ./cmd/safecommit

TOOL="./bin/safecommit scan --no-repo-context --cache-dir corpus/registry-snapshot $OFFLINE"
CORPORA="--corpus corpus/known-good --corpus corpus/seeded"
HOLDOUT="--corpus corpus/holdout"
HOLDOUT2="--corpus corpus/holdout2"

SHA=$(git rev-parse --short HEAD 2>/dev/null || echo "unknown")
DIRTY=""
git diff --quiet 2>/dev/null || DIRTY=" (working tree dirty)"
DATE=$(date +%Y-%m-%d)
GOV=$(go version | awk '{print $3}')
PYV=$(python3 --version 2>&1 | awk '{print $2}')
VER=$(./bin/safecommit --version)

MAIN=$(python3 -m bench eval --tool "$TOOL" $CORPORA 2>/dev/null)
HOLD=$(python3 -m bench eval --tool "$TOOL" $HOLDOUT 2>/dev/null | sed -n '/^corpus/,/^NOISE/p')
CTXTOOL="./bin/safecommit scan --repo-context {context} --cache-dir corpus/registry-snapshot $OFFLINE"
HOLD2=$(python3 -m bench eval --tool "$CTXTOOL" $HOLDOUT2 2>/dev/null | sed -n '/^corpus/,/^NOISE/p')
LOOSE=$(python3 -m bench eval --tool "$TOOL" $CORPORA --match name 2>/dev/null | sed -n '/^corpus/,/^NOISE/p')

# Verdict distribution over the known-good corpus: proves a zero is genuine
# resolution rather than silence.
VERDICTS=$(for f in corpus/known-good/diffs/*.diff; do
    ./bin/safecommit scan --no-repo-context --cache-dir corpus/registry-snapshot $OFFLINE --explain --diff "$f" 2>&1 >/dev/null
  done | awk -F'\t' '{print $1"\t"$2}' | sort | uniq -c | sort -rn)

ref() {  # $1 = tool command, $2 = label
  printf '### %s\n\n```\n%s\n```\n\n' "$2" \
    "$(python3 -m bench eval --tool "$1" $CORPORA 2>/dev/null | sed -n '/^corpus/,$p')"
}

{
cat <<EOF
# SafeCommit benchmark

Generated by \`scripts/benchmark.sh\` — do not edit by hand.

| | |
|---|---|
| date | $DATE |
| commit | \`$SHA\`$DIRTY |
| tool version | \`$VER\` |
| Go | $GOV |
| Python | $PYV |
| registry oracle | \`corpus/registry-snapshot\` (pinned), $MODE |
| matching | file-aware (a finding must agree with the truth's file — PHASE1-NOTES.md R2) |

## Corpora

| corpus | cases | what it measures |
|---|---|---|
| \`corpus/known-good\` | 96 | **noise.** Real merged PRs from 8 major projects. Any finding is a false positive. |
| \`corpus/seeded\` | 20 | **recall.** Diffs with 21 known-fake names, every one PyPI-404-verified. |

## Result

\`\`\`
$MAIN
\`\`\`

### Is the zero real, or just silence?

A detector that never resolves anything also scores zero noise. Every
known-good candidate is therefore accounted for by the reason it was
suppressed; \`SILENT\` would mean "could not determine", and there should be none:

\`\`\`
$VERDICTS
\`\`\`

### Matching mode comparison

Name-only matching (the pre-R2 behaviour, kept for comparison and **not valid
for a published figure**):

\`\`\`
$LOOSE
\`\`\`

If these two differ, the detector is being credited for findings it placed in
the wrong file.

## Holdout — the figure that is not tuned

132 real merged PRs from ten repositories with **no overlap** against the
development set (fastapi, scrapy, celery, sqlalchemy, pydantic, spaCy,
transformers, tornado, airflow, streamlit). Scored **once**, under
\`corpus/HOLDOUT-PROTOCOL.md\`. All cases are clean, so this measures NOISE
only; recall is not measurable here and still comes from the self-authored
seeded set.

\`\`\`
$HOLD
\`\`\`

Every finding here is a false positive. See \`PHASE1-NOTES.md\` R6 for the
diagnosis. Scored in the DEGRADED mode (no repo context), which is why the R6
fix is invisible to this number; it is retained as a historical record.

### Holdout #2 — scored WITH repo context (production mode)

150 merged PRs from ten monorepo/nested-layout repositories (dagster, beam,
ray, prefect, bokeh, mlflow, dbt-core, kedro, metaflow, ansible). No overlap
with the development set or holdout #1.

\`\`\`
$HOLD2
\`\`\`

Diagnosis in \`PHASE1-NOTES.md\` R7. Both holdouts are now SPENT.

## Reference tools

Scored on the same corpora, to show the harness spans the range:

EOF
ref "python3 tools/dummy/never_fire.py" "never_fire — silence (0 noise, 0 recall)"
ref "python3 tools/dummy/always_fire.py" "always_fire — flags every added import (max noise)"

cat <<'EOF'
## How to read these numbers

**They come from the development set, so they are tuned.** Every requirement the
detector satisfies (`PHASE1-NOTES.md` R1–R5) was derived by inspecting this
corpus; it contains only 21 truths; and the seeded cases were authored by this
project. A strong score here demonstrates a working pipeline, not a good
detector.

**The publishable figure comes from the fresh Phase 4 holdout** — a
never-inspected known-good corpus mined from different repositories using the
same seven gates. See `corpus/README.md`.

## Reproducing

```sh
scripts/benchmark.sh          # offline, from the committed cache
scripts/benchmark.sh --live   # permits registry lookups
```
EOF
} > BENCHMARK.md

echo "wrote BENCHMARK.md"
